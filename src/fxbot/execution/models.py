@dataclass(frozen=True, slots=True)
class Quote:
    """Current executable bid/ask quote."""

    symbol: str
    bid: float
    ask: float
    timestamp: datetime

    def __post_init__(self) -> None:
        object.__setattr__(self, "symbol", _symbol(self.symbol))
        object.__setattr__(self, "bid", _positive(self.bid, "bid"))
        object.__setattr__(self, "ask", _positive(self.ask, "ask"))
        object.__setattr__(self, "timestamp", _utc(self.timestamp, "timestamp"))
        if self.ask < self.bid:
            raise ValueError("ask cannot be below bid")

    @property
    def spread(self) -> float:
        return self.ask - self.bid

    @property
    def mid(self) -> float:
        return (self.bid + self.ask) / 2.0


@dataclass(frozen=True, slots=True)
class RiskDecision:
    """Pre-trade authorization result."""

    approved: bool
    reason: str
    approved_quantity: float | None = None

    def __post_init__(self) -> None:
        object.__setattr__(self, "reason", self.reason.strip() or "unspecified")
        if self.approved_quantity is not None:
            object.__setattr__(
                self,
                "approved_quantity",
                _positive(self.approved_quantity, "approved_quantity"),
            )
        if not self.approved and self.approved_quantity is not None:
            raise ValueError("Rejected decisions cannot approve quantity")


@dataclass(frozen=True, slots=True)
class ExecutionEvent:
    """Append-only execution audit record."""

    sequence: int
    timestamp: datetime
    kind: ExecutionEventKind
    message: str
    client_order_id: str | None = None
    broker_order_id: str | None = None
    execution_id: str | None = None
    metadata: Metadata = ()

    def __post_init__(self) -> None:
        if self.sequence < 0:
            raise ValueError("sequence must be non-negative")
        object.__setattr__(self, "timestamp", _utc(self.timestamp, "timestamp"))
        object.__setattr__(self, "kind", ExecutionEventKind(self.kind))
        object.__setattr__(self, "message", self.message.strip() or self.kind.value)
        if self.client_order_id is not None:
            object.__setattr__(
                self,
                "client_order_id",
                _identifier(self.client_order_id, "client_order_id"),
            )
        if self.broker_order_id is not None:
            object.__setattr__(
                self,
                "broker_order_id",
                _identifier(self.broker_order_id, "broker_order_id"),
            )
        if self.execution_id is not None:
            object.__setattr__(
                self,
                "execution_id",
                _identifier(self.execution_id, "execution_id"),
            )
        object.__setattr__(self, "metadata", _metadata(self.metadata))
